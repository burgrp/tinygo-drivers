    PAN211_SetCrcScheme(config.Crc)
    print('setTxPayloadLen')
    PAN211_SetTxPayloadLen(config.TxLen)
    print('setRxPayloadLen')
    PAN211_SetRxPayloadLen(config.RxLen)
    print('SetAddrWidth')
    PAN211_SetAddrWidth(config.TxAddrWidth)
    print('SetTxAddr')
    PAN211_SetTxAddr(config.TxAddr, config.TxAddrWidth)
